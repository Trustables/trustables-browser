import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
await mkdir(new URL("../dist/", import.meta.url), { recursive: true });
const css = await readFile(new URL("../src/widget.css", import.meta.url), "utf8");
await writeFile(new URL("../src/styles.generated.ts", import.meta.url),
  `// Generated by tools/build.mjs; edit widget.css instead.\nexport const widgetCss = ${JSON.stringify(css)};\n`);
for (const file of ["widget.css", "fonts.css"])
  await copyFile(new URL("../src/" + file, import.meta.url), new URL("../dist/" + file, import.meta.url));
